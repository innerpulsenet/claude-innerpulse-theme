// Writes hooks/geometry.ts from the innerpulse-brand kit, so the mod draws the mark at runtime
// without the kit. Usage: node scripts/build-geometry.mjs <path to the kit's scripts/pulse.mjs>
import { writeFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'
import { resolve } from 'node:path'

const kit = await import(pathToFileURL(resolve(process.argv[2])).href)
const { plateD, slotRects, barRects, lightWeights, BRAND, THINK, PULSE } = kit
const r = v => Math.round(v * 100) / 100
const out = {
  plateD: plateD(),
  slots: slotRects().map(s => ({ x: r(s.x), y: r(s.y), w: r(s.w), h: r(s.h), rx: r(s.rx) })),
  bars: barRects().map(b => ({ x: r(b.x), y: r(b.y), w: r(b.w), h: r(b.h), rx: r(b.rx) })),
  light: lightWeights().map(r),
  brand: BRAND,
  think: THINK,
  pulse: PULSE,
}
writeFileSync(new URL('../hooks/geometry.ts', import.meta.url), `// Generated by scripts/build-geometry.mjs from the innerpulse-brand kit; do not edit by hand.
// The plate's outline and slots (viewBox -100..100), the bare beat's bars (viewBox -110..110), how
// strongly each bar is lit (the strike hottest), and the brand's colors and motion constants.
export const GEOMETRY = ${JSON.stringify(out, null, 2)} as const
`)
console.log('slots', out.slots.length, 'bars', out.bars.length)
